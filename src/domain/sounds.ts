/**
 * Sound cues and the user's own sound files.
 *
 * Sounds come from two places: files bundled with the app (src/assets/audio) and files the user
 * chooses in Settings, which are copied into the app's data folder. A user file overrides the bundled
 * one for the same cue; user music tracks are added to any bundled ones.
 */

/** Short sounds for actions in the app. */
export const EFFECT_CUES = [
  'task-created',
  'task-completed',
  'task-undone',
  'task-deleted',
  'task-skipped',
  'error',
] as const
export type EffectCue = (typeof EFFECT_CUES)[number]

/** One sound per notification kind. */
export const NOTIFICATION_CUES = ['reminder', 'due', 'overdue', 'missed'] as const
export type NotificationCue = (typeof NOTIFICATION_CUES)[number]

export const AUDIO_EXTENSIONS = ['mp3', 'ogg', 'wav', 'm4a'] as const
export type AudioFormat = (typeof AUDIO_EXTENSIONS)[number]

export const EFFECT_LABELS: Record<EffectCue, string> = {
  'task-created': 'Task created',
  'task-completed': 'Task completed',
  'task-undone': 'Undo',
  'task-deleted': 'Task deleted',
  'task-skipped': 'Occurrence skipped',
  error: 'Something went wrong',
}

export const NOTIFICATION_LABELS: Record<NotificationCue, string> = {
  reminder: 'Reminder',
  due: 'Due now',
  overdue: 'Overdue',
  missed: 'Missed reminders summary',
}

/** A sound file the user added; `file` is the name it is stored under in the app's data folder. */
export interface UserSound {
  file: string
  originalName: string
  addedAt: string
}

export interface UserTrack extends UserSound {
  id: string
  title: string
}

export interface UserSounds {
  effects: Partial<Record<EffectCue, UserSound>>
  notifications: Partial<Record<NotificationCue, UserSound>>
  music: UserTrack[]
}

export type SoundSlot =
  { kind: 'effect'; cue: EffectCue } | { kind: 'notification'; cue: NotificationCue } | { kind: 'music' }

/** Sub-folder of the sounds directory for each kind of slot. */
export const SOUND_FOLDERS = { effect: 'effects', notification: 'notifications', music: 'music' } as const
export type SoundFolder = (typeof SOUND_FOLDERS)[keyof typeof SOUND_FOLDERS]

const MB = 1024 * 1024
/** Largest file accepted per kind: effects and notification sounds should be short. */
export const MAX_SOUND_BYTES: Record<SoundSlot['kind'], number> = {
  effect: 5 * MB,
  notification: 5 * MB,
  music: 60 * MB,
}
export const MAX_TRACKS = 200

/** Stored file names are generated by the app: lowercase letters, digits and dashes, plus a known extension. */
export const STORED_FILE_PATTERN = /^[a-z0-9-]{1,80}\.(mp3|ogg|wav|m4a)$/

export function emptyUserSounds(): UserSounds {
  return { effects: {}, notifications: {}, music: [] }
}

/** URL the app uses to load a user's sound (served by the main process from the sounds folder only). */
export function userSoundUrl(folder: SoundFolder, file: string): string {
  return `tt-sound://sound/${folder}/${file}`
}

/**
 * Recognizes an audio file by its first bytes rather than trusting the extension, so a renamed
 * non-audio file is rejected. Needs at least the first 12 bytes.
 */
export function detectAudioFormat(bytes: Uint8Array): AudioFormat | null {
  const ascii = (start: number, end: number) => String.fromCharCode(...bytes.subarray(start, end))
  if (bytes.length < 12) return null
  if (ascii(0, 3) === 'ID3') return 'mp3'
  if (bytes[0] === 0xff && (bytes[1] & 0xe0) === 0xe0) return 'mp3' // MPEG audio frame sync
  if (ascii(0, 4) === 'OggS') return 'ogg'
  if (ascii(0, 4) === 'RIFF' && ascii(8, 12) === 'WAVE') return 'wav'
  if (ascii(4, 8) === 'ftyp') return 'm4a'
  return null
}

/** "01-calm_morning" → "Calm morning" */
export function titleFromFileName(name: string): string {
  const words = name
    .replace(/\.[a-z0-9]+$/i, '')
    .replace(/^\d+[\s._-]*/, '')
    .replace(/[_-]+/g, ' ')
    .replace(/\s+/g, ' ')
    .trim()
  const text = words || name
  return text.charAt(0).toUpperCase() + text.slice(1)
}

export function folderFor(slot: SoundSlot): SoundFolder {
  return SOUND_FOLDERS[slot.kind]
}

/**
 * Puts a new file into a slot. For an effect or notification it replaces any previous file, which
 * is returned so it can be deleted; music tracks are appended.
 */
export function assignSound(
  sounds: UserSounds,
  slot: SoundSlot,
  entry: UserSound,
  trackId: string,
): { sounds: UserSounds; replacedFile: string | null } {
  const next = structuredClone(sounds)
  switch (slot.kind) {
    case 'effect': {
      const replaced = next.effects[slot.cue]?.file ?? null
      next.effects[slot.cue] = entry
      return { sounds: next, replacedFile: replaced }
    }
    case 'notification': {
      const replaced = next.notifications[slot.cue]?.file ?? null
      next.notifications[slot.cue] = entry
      return { sounds: next, replacedFile: replaced }
    }
    case 'music':
      next.music.push({ ...entry, id: trackId, title: titleFromFileName(entry.originalName) })
      return { sounds: next, replacedFile: null }
  }
}

/** Removes a user sound (a music track needs its id); returns the stored file that is no longer used. */
export function removeSound(
  sounds: UserSounds,
  slot: SoundSlot,
  trackId?: string,
): { sounds: UserSounds; removedFile: string | null } {
  const next = structuredClone(sounds)
  let removed: string | null
  if (slot.kind === 'effect') {
    removed = next.effects[slot.cue]?.file ?? null
    delete next.effects[slot.cue]
  } else if (slot.kind === 'notification') {
    removed = next.notifications[slot.cue]?.file ?? null
    delete next.notifications[slot.cue]
  } else {
    const track = next.music.find((t) => t.id === trackId)
    removed = track?.file ?? null
    next.music = next.music.filter((t) => t.id !== trackId)
  }
  return { sounds: next, removedFile: removed }
}

/** Every stored file still referenced, as "folder/file". */
export function referencedSoundFiles(sounds: UserSounds): Set<string> {
  const files = new Set<string>()
  for (const s of Object.values(sounds.effects)) if (s) files.add(`effects/${s.file}`)
  for (const s of Object.values(sounds.notifications)) if (s) files.add(`notifications/${s.file}`)
  for (const t of sounds.music) files.add(`music/${t.file}`)
  return files
}
